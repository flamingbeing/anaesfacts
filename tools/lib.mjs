// Shared helpers: find topic files and read their front matter (a small YAML subset: `key: value` and `[a, b]` lists).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

export const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
export const AREAS = ['drugs', 'regional', 'airway', 'comorbidities', 'procedures', 'physiology', 'equipment', 'crises', 'other'];
export const STATUSES = ['verified', 'draft'];

export function topicFiles() {
  const dir = path.join(ROOT, 'topics');
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const area of fs.readdirSync(dir).sort()) {
    const sub = path.join(dir, area);
    if (!fs.statSync(sub).isDirectory()) continue;
    for (const f of fs.readdirSync(sub).sort()) if (f.endsWith('.md')) out.push(`topics/${area}/${f}`);
  }
  return out;
}

export function frontMatter(text) {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!m) return null;
  const data = {};
  for (const line of m[1].split('\n')) {
    const kv = /^([a-z_]+):\s*(.*?)\s*(#.*)?$/.exec(line);
    if (!kv) continue;
    let v = kv[2];
    if (/^\[.*\]$/.test(v)) v = v.slice(1, -1).split(',').map(s => s.trim()).filter(Boolean);
    data[kv[1]] = v;
  }
  return data;
}

export function buildIndex() {
  return topicFiles().map(p => {
    const fm = frontMatter(fs.readFileSync(path.join(ROOT, p), 'utf8')) || {};
    return { path: p, title: fm.title || '', area: fm.area || '', status: fm.status || '', verified_on: fm.verified_on || '', tags: fm.tags || [], aliases: fm.aliases || [], related: fm.related || [] };
  });
}

export const indexText = () => JSON.stringify(buildIndex(), null, 1) + '\n';

// Generated "Related" footer: the topic's own `related` list (area/slug or bare slug) plus topics that list it,
// keeping only files that exist. Rewritten by build-index between the markers; never edit by hand.
export const REL_START = '<!-- related:start (generated) -->';
export const REL_END = '<!-- related:end -->';
const AREA_TITLES = { drugs: 'Drugs', regional: 'Regional', airway: 'Airway', comorbidities: 'Comorbidities', procedures: 'Procedures', physiology: 'Physiology', equipment: 'Equipment', crises: 'Crises', other: 'Other' };

function resolver(index) {
  const byKey = new Map(), byBase = new Map();
  for (const t of index) {
    const key = t.path.replace(/^topics\//, '').replace(/\.md$/, '');
    byKey.set(key, t);
    const base = key.split('/')[1];
    byBase.set(base, byBase.has(base) ? null : t);
  }
  return ref => { const r = ref.replace(/\.md$/, ''); return byKey.get(r) || byBase.get(r.split('/').pop()) || null; };
}

export function relatedMap(index = buildIndex()) {
  const find = resolver(index), map = new Map(index.map(t => [t.path, []]));
  const add = (from, to) => { if (to && to.path !== from.path && !map.get(from.path).includes(to)) map.get(from.path).push(to); };
  for (const t of index) for (const r of t.related) add(t, find(r));
  for (const t of index) for (const r of t.related) { const o = find(r); if (o) add(o, t); }
  return map;
}

export function withRelated(text, p, links) {
  const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const body = text.replace(new RegExp(`\\n*${esc(REL_START)}[\\s\\S]*?${esc(REL_END)}\\n*$`), '').replace(/\n*$/, '\n');
  if (!links.length) return body;
  const rel = links.map(t => `- [${t.title}](${path.relative(path.dirname(p), t.path)})`).join('\n');
  return `${body}\n${REL_START}\n## Related\n${rel}\n${REL_END}\n`;
}

export function contentsText(index = buildIndex()) {
  const out = ['# Contents', '', 'Generated by `node tools/build-index.mjs` from the topic files; do not edit by hand.', ''];
  for (const area of AREAS) {
    const ts = index.filter(t => t.area === area).sort((a, b) => a.title.localeCompare(b.title));
    if (!ts.length) continue;
    out.push(`## ${AREA_TITLES[area]} (${ts.length})`, '');
    for (const t of ts) out.push(`- [${t.title}](${t.path})${t.aliases.length ? ` (${t.aliases.join(', ')})` : ''}${t.status === 'draft' ? ' *draft*' : ''}`);
    out.push('');
  }
  return out.join('\n');
}

// Facts: every bullet line (any depth) under a `## ` section of a topic, except Flashcards and the generated Related
// footer. Fact id = `<area>/<slug>#<6 hex of sha1 of the normalised line>`; edit a line and its id changes, so its old
// questions drop out. Identical lines in one topic share an id and are listed once.
export const NON_FACT_SECTIONS = ['Flashcards', 'Related'];
export const normaliseLine = t => t.replace(/[*_`]/g, '').replace(/\s+/g, ' ').trim().toLowerCase();
export const factHash = t => crypto.createHash('sha1').update(normaliseLine(t)).digest('hex').slice(0, 6);
export const topicKey = p => p.replace(/^topics\//, '').replace(/\.md$/, '');

export function factsOf(text, p) {
  const body = text.replace(/^---\n[\s\S]*?\n---\n/, '').replace(new RegExp(`${REL_START}[\\s\\S]*?${REL_END}`), '');
  const key = topicKey(p), seen = new Set(), out = [];
  let section = null;
  for (const line of body.split('\n')) {
    const h = /^##\s+(.*?)\s*$/.exec(line);
    if (h) { section = h[1]; continue; }
    const b = /^\s*[-*]\s+(.*\S)\s*$/.exec(line);
    if (!b || !section || NON_FACT_SECTIONS.includes(section)) continue;
    const id = `${key}#${factHash(b[1])}`;
    if (seen.has(id)) continue;
    seen.add(id);
    out.push({ id, topic: key, section, text: b[1] });
  }
  return out;
}

export function buildFacts() {
  return topicFiles().flatMap(p => factsOf(fs.readFileSync(path.join(ROOT, p), 'utf8'), p));
}
// facts.json leaves out `topic` (it is the part of the id before #) to keep the file small for phones.
export const factsText = () => JSON.stringify(buildFacts().map(({ id, section, text }) => ({ id, section, text }))) + '\n';

// Questions: questions/<area>/<slug>.json = { "topic": "<area>/<slug>", "questions": [...] }.
export const KINDS = ['mcq', 'statement', 'blank'];
export function questionFiles() {
  const dir = path.join(ROOT, 'questions');
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const area of fs.readdirSync(dir).sort()) {
    const sub = path.join(dir, area);
    if (!fs.statSync(sub).isDirectory()) continue;
    for (const f of fs.readdirSync(sub).sort()) if (f.endsWith('.json')) out.push(`questions/${area}/${f}`);
  }
  return out;
}
export const numbersIn = t => (t.match(/\d+(?:[.,]\d+)*/g) || []).map(n => n.replace(/,(?=\d{3}\b)/g, ''));

// Lower-case words only, so "3-5 mcg" and "3–5 mcg." compare equal.
const squash = t => ` ${String(t).toLowerCase().replace(/[^\p{L}\p{N}.]+/gu, ' ').replace(/\.(?!\d)/g, ' ').replace(/\s+/g, ' ').trim()} `;

// Returns a list of problems with one question against the fact index (Map id -> fact).
export function questionProblems(q, facts, topic) {
  const bad = [];
  if (!q || typeof q !== 'object') return ['not an object'];
  const fact = facts.get(q.fact_id);
  if (!fact) bad.push(`fact_id "${q.fact_id}" does not exist`);
  else if (fact.topic !== topic) bad.push(`fact_id "${q.fact_id}" belongs to another topic`);
  if (!KINDS.includes(q.kind)) bad.push(`kind must be one of ${KINDS.join(', ')}`);
  if (typeof q.stem !== 'string' || !q.stem.trim()) bad.push('stem missing');
  if (/this topic/i.test(q.stem || '')) bad.push('stem must not say "this topic"');
  if (!q.model || typeof q.model !== 'string') bad.push('model missing');
  if (!/^\d{4}-\d{2}-\d{2}$/.test(q.date || '')) bad.push('date must be YYYY-MM-DD');
  let answerText = null;
  if (q.kind === 'mcq') {
    const o = q.options;
    if (!Array.isArray(o) || o.length < 3 || o.length > 5 || o.some(x => typeof x !== 'string' || !x.trim())) bad.push('mcq needs 3-5 non-empty string options');
    else {
      if (new Set(o.map(squash)).size !== o.length) bad.push('mcq options must differ');
      if (!Number.isInteger(q.answer) || q.answer < 0 || q.answer >= o.length) bad.push('mcq answer must be the index of exactly one option');
      else {
        answerText = o[q.answer];
        const a = squash(answerText);
        o.forEach((x, i) => {
          const d = squash(x);
          if (i !== q.answer && d !== a && (d.includes(a) || a.includes(d))) bad.push(`option "${x}" shares the answer's text`);
        });
      }
    }
  } else if (q.kind === 'statement' || q.kind === 'blank') {
    if (q.options !== undefined) bad.push(`${q.kind} must not have options`);
    if (typeof q.answer !== 'string' || !q.answer.trim()) bad.push(`${q.kind} answer must be a non-empty string`);
    else answerText = q.answer;
    if (q.kind === 'blank' && !/_{3,}/.test(q.stem || '')) bad.push('blank stem needs a ____ gap');
  }
  if (fact && q.kind === 'blank' && answerText !== null && !squash(fact.text).includes(squash(answerText))) bad.push('blank answer is not in the fact');
  if (q.kind === 'blank' && answerText !== null && squash(q.stem || '').includes(squash(answerText))) bad.push('blank stem gives the answer away');
  if (fact && answerText !== null) {
    const have = numbersIn(fact.text);
    for (const n of numbersIn(answerText)) if (!have.includes(n)) bad.push(`number "${n}" in the answer is not in the fact`);
  }
  return bad;
}
